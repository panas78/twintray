#!/usr/bin/env bash
# install.sh — install TwinTray for the current user.
#
#   ./install.sh                  install, with start-at-login enabled
#   ./install.sh --no-autostart   install without the autostart entry
#   ./install.sh --uninstall      remove every file this script installs
#   PREFIX=/tmp/x ./install.sh    install somewhere else (for round-trip tests)
#
# Nothing here needs root: the app lives in PREFIX (default ~/.local) and talks
# to the system only through `systemctl start/stop twingate`, which the polkit
# rule in the sibling MySettings repo makes passwordless.

set -euo pipefail

APP_ID="io.github.panas78.Twintray"
CMD="twintray"
PREFIX="${PREFIX:-$HOME/.local}"
BINDIR="$PREFIX/bin"
APPDIR="$PREFIX/share/twintray"
DATADIR="$PREFIX/share"
ICONTHEME="$DATADIR/icons/hicolor"
SIZES=(16 22 24 32 48 64 128 256 512)

SRC="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

AUTOSTART=1
UNINSTALL=0
for arg in "$@"; do
    case "$arg" in
    --no-autostart) AUTOSTART=0 ;;
    --uninstall) UNINSTALL=1 ;;
    -h | --help)
        sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
        exit 0
        ;;
    *)
        echo "Unknown option: $arg" >&2
        exit 2
        ;;
    esac
done

say() { printf '  %s\n' "$*"; }
step() { printf '\n== %s\n' "$*"; }

# --------------------------------------------------------------------- deps
PYTHON=/usr/bin/python3

check_deps() {
    step "Checking dependencies"
    if [[ ! -x "$PYTHON" ]]; then
        echo "ERROR: $PYTHON not found. This app is pinned to the system python." >&2
        exit 1
    fi
    if ! "$PYTHON" - <<'PY'
import sys
try:
    import gi
    gi.require_version("Gtk", "4.0")
    gi.require_version("Adw", "1")
    from gi.repository import Gtk, Adw
    import cairo
except Exception as exc:
    print(exc, file=sys.stderr)
    sys.exit(1)
PY
    then
        cat >&2 <<'EOF'
ERROR: the GTK4 stack for PyGObject is missing.

Install it from the distro — never from pip, because PyGObject is a binding over
system shared libraries and a venv copy cannot see the typelibs:

  Fedora: sudo dnf install python3-gobject gtk4 libadwaita python3-cairo desktop-file-utils
  Debian: sudo apt install python3-gi gir1.2-gtk-4.0 gir1.2-adw-1 python3-cairo desktop-file-utils
EOF
        exit 1
    fi
    say "python: $("$PYTHON" -V 2>&1)"
    say "PyGObject + GTK4 + libadwaita: ok"

    if ! command -v twingate >/dev/null 2>&1; then
        say "WARNING: the twingate CLI is not on PATH; the app will report it in doctor."
    else
        say "twingate: $(twingate version 2>/dev/null | head -1)"
    fi
}

# ---------------------------------------------------------------- uninstall
do_uninstall() {
    step "Removing TwinTray"
    rm -f "$BINDIR/$CMD"
    say "removed $BINDIR/$CMD"

    rm -rf "$APPDIR"
    say "removed $APPDIR"

    rm -f "$DATADIR/applications/$APP_ID.desktop"
    rm -f "$DATADIR/metainfo/$APP_ID.metainfo.xml"
    say "removed desktop entry and metainfo"

    for size in "${SIZES[@]}"; do
        rm -f "$ICONTHEME/${size}x${size}/apps/$CMD.png"
    done
    say "removed ${#SIZES[@]} icon sizes"

    rm -f "${XDG_CONFIG_HOME:-$HOME/.config}/autostart/$APP_ID.desktop"
    say "removed autostart entry"

    command -v update-desktop-database >/dev/null 2>&1 &&
        update-desktop-database "$DATADIR/applications" 2>/dev/null || true
    command -v gtk-update-icon-cache >/dev/null 2>&1 &&
        gtk-update-icon-cache -qtf "$ICONTHEME" 2>/dev/null || true

    echo
    echo "TwinTray removed. Your preferences are still at:"
    echo "  ${XDG_CONFIG_HOME:-$HOME/.config}/twintray/prefs.json"
    exit 0
}

# ------------------------------------------------------------------ install
check_deps
[[ $UNINSTALL -eq 1 ]] && do_uninstall

step "Installing the package"
rm -rf "$APPDIR"
mkdir -p "$APPDIR" "$BINDIR"
cp -a "$SRC/twintray" "$APPDIR/"
# Payload hygiene: the installed tree is not the source tree.
rm -rf "$APPDIR/twintray/__pycache__"
say "package -> $APPDIR/twintray"

step "Writing the launcher"
cat >"$BINDIR/$CMD" <<EOF
#!/bin/sh
# Generated by install.sh — pins the system interpreter and the install dir, so
# the app behaves the same regardless of the caller's shell, venv or PATH.
PYTHONPATH="$APPDIR"
export PYTHONPATH
exec $PYTHON -B -m twintray.cli "\$@"
EOF
chmod 0755 "$BINDIR/$CMD"
say "launcher -> $BINDIR/$CMD"

step "Installing the desktop entry and metainfo"
mkdir -p "$DATADIR/applications" "$DATADIR/metainfo"
sed "s|@BINDIR@|$BINDIR|g" "$SRC/data/$APP_ID.desktop.in" \
    >"$DATADIR/applications/$APP_ID.desktop"
install -m 0644 "$SRC/data/$APP_ID.metainfo.xml" "$DATADIR/metainfo/"
say "entry  -> $DATADIR/applications/$APP_ID.desktop"

step "Installing icons"
for size in "${SIZES[@]}"; do
    src="$SRC/data/icons/hicolor/${size}x${size}/apps/$CMD.png"
    [[ -f $src ]] || {
        echo "ERROR: missing icon source: $src" >&2
        exit 1
    }
    mkdir -p "$ICONTHEME/${size}x${size}/apps"
    install -m 0644 "$src" "$ICONTHEME/${size}x${size}/apps/$CMD.png"
done
say "${#SIZES[@]} sizes -> $ICONTHEME"

step "Refreshing caches"
command -v update-desktop-database >/dev/null 2>&1 &&
    update-desktop-database "$DATADIR/applications" 2>/dev/null || true
command -v gtk-update-icon-cache >/dev/null 2>&1 &&
    gtk-update-icon-cache -qtf "$ICONTHEME" 2>/dev/null || true
say "done"

if [[ $AUTOSTART -eq 1 ]]; then
    step "Enabling start at login"
    # Generated by the app, not by this script: start-at-login is also a GUI
    # switch and a CLI subcommand, and a third definition here would drift.
    "$BINDIR/$CMD" autostart on
else
    step "Leaving start at login alone"
fi

step "Validating"
fail=0
if command -v desktop-file-validate >/dev/null 2>&1; then
    # A malformed entry appears in NO menu at all, silently — the one failure
    # worth catching here. And do not claim "valid" without asking.
    if desktop-file-validate "$DATADIR/applications/$APP_ID.desktop"; then
        say "desktop entry valid"
    else
        say "desktop entry INVALID (see above)"
        fail=1
    fi
else
    say "desktop-file-validate not installed; skipped"
fi
if command -v appstreamcli >/dev/null 2>&1; then
    if appstreamcli validate --no-net "$DATADIR/metainfo/$APP_ID.metainfo.xml" >/dev/null 2>&1; then
        say "metainfo valid"
    else
        say "appstreamcli reported notes (non-fatal)"
    fi
fi

step "doctor"
"$BINDIR/$CMD" doctor || true

echo
echo "TwinTray installed."
echo "  Run it:        $CMD window     (or start it from your app menu)"
echo "  Tray only:     $CMD tray"
echo "  Status:        $CMD status"
if [[ ":$PATH:" != *":$BINDIR:"* ]]; then
    echo
    echo "NOTE: $BINDIR is not on your PATH."
fi
exit $fail
